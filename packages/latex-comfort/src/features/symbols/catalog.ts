export type LatexSymbol = {
  command: string;
  label: string;
  category: string;
  keywords?: readonly string[];
};

function symbol(
  command: string,
  label: string,
  category: string,
  keywords: readonly string[] = [],
): LatexSymbol {
  const normalizedCommand = `\\${command.replace(/^\\+/, "")}`;
  return keywords.length > 0
    ? { command: normalizedCommand, label, category, keywords }
    : { command: normalizedCommand, label, category };
}

