function normalize(value: string): string {
  return value.toLowerCase();
}

/**
 * Search the symbol catalog case-insensitively. A leading backslash on a
 * command query is optional, and an empty query returns the catalog order.
 */
export function searchLatexSymbols(query: string): LatexSymbol[] {
  const normalizedQuery = normalize(query.trim().replace(/^\\+/, ""));
  if (!normalizedQuery) return [...LATEX_SYMBOLS];

  return LATEX_SYMBOLS.filter((symbol) => {
    const command = normalize(symbol.command.replace(/^\\+/, ""));
    return (
      command.includes(normalizedQuery) ||
      normalize(symbol.label).includes(normalizedQuery) ||
      normalize(symbol.category).includes(normalizedQuery) ||
      symbol.keywords?.some((keyword) => normalize(keyword).includes(normalizedQuery)) === true
    );
  });
}
